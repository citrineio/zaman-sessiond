const assert = require('node:assert/strict');
const {fixture} = require('./menu-controller-regression.cjs');
const state = fixture();
state.mainEntries = [{key:'resume'}, {key:'emulator-menu'}];
state.emulatorMenuAvailable = true;
state.foreground = 'game';
state.selected = 1;
state.input('ui_accept', 1);
assert.equal(state.pendingEmulatorMenu, false, 'hold must not trigger menu action');
assert.equal(state.menuOpen, true);
state.input('ui_accept', 0);
assert.equal(state.pendingEmulatorMenu, true);
assert.equal(state.menuOpen, false);
assert.equal(state.closing, true);
assert.equal(state.emulatorMenuAction.running, false, 'do not inject while overlay still owns input');
state.receive(JSON.stringify({type:'closed'}));
assert.equal(state.emulatorMenuAction.running, false);
state.receive(JSON.stringify({type:'helper-idle',protocol:1}));
assert.equal(state.emulatorMenuAction.running, true, 'send only after controller lease restored');
assert.equal(state.pendingEmulatorMenu, false);
const unsupported = fixture();
unsupported.mainEntries = [{key:'resume'}, {key:'emulator-menu'}];
unsupported.selected = 1;
unsupported.emulatorMenuAvailable = false;
unsupported.input('ui_accept',1);
unsupported.input('ui_accept',0);
assert.equal(unsupported.pendingEmulatorMenu,false);
assert.equal(unsupported.menuOpen,true);
console.log('PASS: controller release, input lease and capability guards for Emulator Menu.');
