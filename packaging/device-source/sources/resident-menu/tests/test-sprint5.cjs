const assert = require('node:assert/strict');
const {fixture} = require('./menu-controller-regression.cjs');
const id = 'a'.repeat(32);
const invalid = fixture(); invalid.foreground = 'library';
invalid.openTransaction('../../run');
assert.equal(invalid.pendingStoreAction, null);
const game = fixture(); game.foreground = 'game';
game.openTransaction(id);
assert.equal(game.menuOpen, true);
assert.equal(game.pendingStoreAction, null);
assert.match(game.storeNotice, /library/);
const library = fixture(); library.foreground = 'library';
library.openTransaction(id);
assert.equal(library.closing, true);
assert.equal(library.storeAction.running, false);
assert.equal(library.pendingStoreAction.target, id);
library.receive(JSON.stringify({type:'closed'}));
assert.equal(library.storeAction.running, false);
library.receive(JSON.stringify({type:'helper-idle', protocol:1}));
assert.equal(library.storeAction.running, true);
assert.equal(library.storeRequest.target, id);
const activity = fixture('transactions');
activity.move(1); activity.activate(); activity.back();
assert.equal(activity.page, 'settings');
console.log('PASS: typed transaction target, gameplay guard, activity navigation and input-lease handoff.');
